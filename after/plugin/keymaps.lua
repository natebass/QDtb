map("n", "<leader>xl", function()
	local success, err = pcall(function()
		if vim.fn.getloclist(0, { winid = 0 }).winid ~= 0 then
			vim.cmd.lclose()
		else
			vim.cmd.lopen()
		end
	end)
	if not success and err then
		vim.notify(err, vim.log.levels.ERROR)
	end
end, { desc = "Location List" })

	local success, err = pcall(function()
		if vim.fn.getqflist({ winid = 0 }).winid ~= 0 then
			vim.cmd.cclose()
		else
			vim.cmd.copen()
		end
	end)
	if not success and err then
		vim.notify(err, vim.log.levels.ERROR)
	end
end, { desc = "Quickfix List" })
